import type { SkeletonModuleDefinition } from '../module-types'
import { hasFeatureWithKeyword } from '../module-types'
import { registerModule } from '../modules-registry'

const NEWSLETTER_KEYWORDS = [
  'newsletter', 'mailing_list', 'subscribe_newsletter', 'subscribe_mail',
  'unsubscribe', 'email_subscribe',
]

const newsletterModule: SkeletonModuleDefinition = {
  id: 'newsletter',
  displayName: 'Newsletter Subscribe',
  description: '訪客訂閱電子報 → double-opt-in confirmation token + unsubscribe link',

  ddl: `CREATE TABLE IF NOT EXISTS newsletter_subscribers (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email VARCHAR(200) NOT NULL UNIQUE,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  confirmation_token TEXT,
  confirmed_at TIMESTAMPTZ,
  unsubscribed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_newsletter_subscribers_status ON newsletter_subscribers(status);
CREATE INDEX IF NOT EXISTS idx_newsletter_subscribers_token ON newsletter_subscribers(confirmation_token) WHERE confirmation_token IS NOT NULL;`,

  entityMapping: {
    NewsletterSubscriber: 'newsletter_subscribers',
  },

  canonicalFeatures: [
    {
      name: 'Subscribe Newsletter',
      actionName: 'subscribe_newsletter',
      method: 'POST',
      path: '/api/newsletter/subscribe',
    },
    {
      name: 'Unsubscribe Newsletter',
      actionName: 'unsubscribe_newsletter',
      method: 'POST',
      path: '/api/newsletter/unsubscribe',
    },
  ],

  locked: [
    'email format validation (RFC 5322 lite)',
    'confirmation_token generated by crypto.randomBytes(24)',
    'INSERT ... ON CONFLICT (email) DO UPDATE to reactivate',
    'status enum: pending / active / unsubscribed',
  ],

  slots: {
    require_double_opt_in: {
      type: 'boolean',
      default: true,
      description: '是否要求 email 確認（true → status 從 pending 開始，需點確認信才轉 active）',
    },
  },

  detect(input) {
    const k = hasFeatureWithKeyword(input.features ?? [], NEWSLETTER_KEYWORDS)
    return {
      matched: k.matched,
      score: 20,
      rule: 'newsletterModule',
      evidence: k.evidence.slice(0, 3).join(', '),
    }
  },

  generateFeatures() {
    return [
      {
        name: 'Subscribe Newsletter',
        actionName: 'subscribe_newsletter',
        skeletonModule: 'newsletter',
        content: `# Action: subscribe_newsletter
# [POST] /api/newsletter/subscribe
# Summary: Subscribe to newsletter

Feature: Subscribe Newsletter
  訪客送出 email 訂閱電子報；首次訂閱 status=pending，重複訂閱 reactivate

  Background:
    Given 現在時間為 "2026-01-01T12:00:00Z"

  Example: First-time subscribe (status=pending)
    When (No Actor) Subscribe Newsletter, call table:
      | email             |
      | jane@example.com  |
    Then Subscribe Newsletter(201)回應, with table:
      | email             | status  |
      | jane@example.com  | pending |
    And 應該存在一個NewsletterSubscriber, with table:
      | email             | status  |
      | jane@example.com  | pending |

  Example: Reject invalid email
    When (No Actor) Subscribe Newsletter, call table:
      | email          |
      | not-an-email   |
    Then 操作失敗
`,
      },
      {
        name: 'Unsubscribe Newsletter',
        actionName: 'unsubscribe_newsletter',
        skeletonModule: 'newsletter',
        content: `# Action: unsubscribe_newsletter
# [POST] /api/newsletter/unsubscribe
# Summary: Unsubscribe from newsletter

Feature: Unsubscribe Newsletter
  訪客取消訂閱：status → unsubscribed + unsubscribed_at 設值

  Background:
    Given 現在時間為 "2026-01-02T12:00:00Z"
    And 準備一個NewsletterSubscriber, with table:
      | >NewsletterSubscriber1.id | email             | status |
      | $notnull                  | jane@example.com  | active |

  Example: Active subscriber unsubscribes
    When (No Actor) Unsubscribe Newsletter, call table:
      | email             |
      | jane@example.com  |
    Then Unsubscribe Newsletter(200)回應, with table:
      | email             | status       |
      | jane@example.com  | unsubscribed |
    And 應該存在一個NewsletterSubscriber, with table:
      | email             | status       |
      | jane@example.com  | unsubscribed |
`,
      },
    ]
  },

  generateServerActions() {
    return [
      {
        actionName: 'subscribe_newsletter',
        filePath: 'lib/actions/subscribe-newsletter.ts',
        fnName: 'subscribeNewsletter',
        content: `import { sql } from '@/lib/db'
import crypto from 'crypto'

const EMAIL_RE = /^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$/

export async function subscribeNewsletter(input: any): Promise<any> {
  const email = typeof input?.email === 'string' ? input.email.trim().toLowerCase() : ''
  if (!email) throw new Error('email is required')
  if (!EMAIL_RE.test(email)) throw new Error('Invalid email format')

  const token = crypto.randomBytes(24).toString('hex')

  const [row] = await sql\`
    INSERT INTO newsletter_subscribers (email, status, confirmation_token)
    VALUES (\${email}, 'pending', \${token})
    ON CONFLICT (email) DO UPDATE SET
      status = CASE
        WHEN newsletter_subscribers.status = 'unsubscribed' THEN 'pending'
        ELSE newsletter_subscribers.status
      END,
      confirmation_token = COALESCE(newsletter_subscribers.confirmation_token, EXCLUDED.confirmation_token),
      unsubscribed_at = NULL
    RETURNING id, email, status, created_at
  \`

  return { __status: 201, ...row }
}
`,
      },
      {
        actionName: 'unsubscribe_newsletter',
        filePath: 'lib/actions/unsubscribe-newsletter.ts',
        fnName: 'unsubscribeNewsletter',
        content: `import { sql } from '@/lib/db'

export async function unsubscribeNewsletter(input: any): Promise<any> {
  const email = typeof input?.email === 'string' ? input.email.trim().toLowerCase() : ''
  if (!email) throw new Error('email is required')

  const existing = await sql\`SELECT id FROM newsletter_subscribers WHERE email = \${email}\`
  if (existing.length === 0) throw new Error('Subscriber not found')

  const [row] = await sql\`
    UPDATE newsletter_subscribers
    SET status = 'unsubscribed', unsubscribed_at = NOW()
    WHERE email = \${email}
    RETURNING id, email, status, unsubscribed_at
  \`

  return { __status: 200, ...row }
}
`,
      },
    ]
  },
}

registerModule(newsletterModule)

export default newsletterModule
