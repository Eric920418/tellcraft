import re

import jsonpath
from behave import then

# Import ISAFeatureArgumentResolver with fallback for different contexts
try:
    from steps.helpers.isa_resolver import ISAFeatureArgumentResolver
except ModuleNotFoundError:
    from test.features.steps.helpers.isa_resolver import ISAFeatureArgumentResolver


@then("操作失敗")
def operation_failed(context):
    """Verify the API operation failed with a 4xx client error status code."""
    response = context.last_response
    assert response is not None, "Expected a previous API response, but got None"
    assert response.status_code >= 400, (
        f"Expected error status code (>=400), but got {response.status_code}"
    )


@then("{api_summary}({expected_status_code:d})回應, with table:")
def response_matches_table_with_api_summary(
    context, api_summary: str, expected_status_code: int
):
    """Verify API response fields match expected values using JSONPath.

    Args:
        api_summary: The API operation summary (e.g., "玩家加入遊戲")
        expected_status_code: The expected HTTP status code (e.g., 200)

    Supports type coercion and special values:
    - "$notnull": field must exist and not be null
    - "$variable": resolve variable from context (VAR-System)
    - "&constraint(...)": evaluate constraint assertion (CAS-System)
    - "@time(...)": convert time expression (TIME-System)
    - "true"/"false": boolean comparison
    - Numeric patterns: automatic int/float conversion
    - Others: string comparison

    Example table:
        | gameId      | playerRole | score        |
        | $savedGameId| P1         | &gt(50)&lt(100) |
        | result.a    | $notnull   | @time(now)   |
    """
    response = context.last_response
    assert response is not None, "Expected a previous API response, but got None"

    # Verify HTTP status code matches the expected status code
    assert response.status_code == expected_status_code, (
        f"API '{api_summary}' expected status code {expected_status_code}, but got {response.status_code}"
    )

    assert context.table is not None, "Expected a data table, but got None"
    assert len(context.table.rows) > 0, "Expected non-empty data table"

    response_json = response.json()

    # Initialize ISA resolver
    resolver = ISAFeatureArgumentResolver(context)

    for row in context.table:
        row_dict = dict(zip(row.headings, row.cells, strict=False))
        for field_path, expected_value in row_dict.items():
            json_path = f"$.{field_path}"

            try:
                matches = jsonpath.findall(json_path, response_json)
                assert len(matches) > 0, (
                    f"JSON path '{field_path}' not found in response"
                )
                actual_value = matches[0]
            except Exception as e:
                raise AssertionError(
                    f"Failed to parse JSON path '{field_path}': {e}"
                ) from e

            # Use ISA resolver for unified VAR/CAS/TIME handling
            try:
                resolved_expected = resolver.resolve_and_validate(
                    expected_value, actual_value, field_path, "Response"
                )

                # Skip further comparisons if CAS constraint already passed
                if resolver.is_constraint_expression(expected_value):
                    continue

                # Otherwise, perform traditional comparison
                if expected_value == "$notnull":
                    # Already handled by resolver
                    pass
                elif expected_value in ("true", "false"):
                    expected_bool = expected_value == "true"
                    assert bool(actual_value) == expected_bool, (
                        f"JSON path '{field_path}' mismatch. Expected: {expected_bool}, Actual: {actual_value}"
                    )
                elif re.match(r"^-?\d+$", str(resolved_expected)):
                    expected_int = int(resolved_expected)
                    assert int(actual_value) == expected_int, (
                        f"JSON path '{field_path}' mismatch. Expected: {expected_int}, Actual: {actual_value}"
                    )
                elif re.match(r"^-?\d+\.\d+$", str(resolved_expected)):
                    expected_float = float(resolved_expected)
                    assert float(actual_value) == expected_float, (
                        f"JSON path '{field_path}' mismatch. Expected: {expected_float}, Actual: {actual_value}"
                    )
                else:
                    assert str(actual_value) == str(resolved_expected), (
                        f"JSON path '{field_path}' mismatch. Expected: {resolved_expected}, Actual: {actual_value}"
                    )
            except AssertionError:
                raise  # Re-raise assertion errors as-is
            except Exception as e:
                raise AssertionError(
                    f"Error validating field '{field_path}': {e}"
                ) from e
